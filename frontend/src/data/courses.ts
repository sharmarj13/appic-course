export function getCourseBySlug(slug: string): Course | undefined {
  return COURSES.find((course) => course.slug === slug);
}

export function getRelatedCourses(currentSlug: string, category: string, limit = 3): Course[] {
  const sameCategory = COURSES.filter((c) => c.slug !== currentSlug && c.category === category);
  const others = COURSES.filter((c) => c.slug !== currentSlug && c.category !== category);
  return [...sameCategory, ...others].slice(0, limit);
}
